// Print the SQL for Better Auth's tables, as configured in src/auth.ts (magic link plugin, database rate limit).
// Usage (from web/worker): node scripts/auth-schema.mjs > ../migrations/0001_better_auth.sql
// D1 is SQLite, so an in-memory node:sqlite database produces the same DDL. test/schema.test.ts checks that
// the applied migrations leave nothing for Better Auth to create, so drift from src/auth.ts fails the tests.
import { readFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { betterAuth } from "better-auth";
import { getMigrations } from "better-auth/db/migration";
import { magicLink } from "better-auth/plugins";

const auth = betterAuth({
  database: new DatabaseSync(":memory:"),
  secret: "schema-generation-only-schema-generation-only",
  baseURL: "http://localhost:8787",
  rateLimit: { enabled: true, storage: "database" },
  plugins: [magicLink({ sendMagicLink: async () => {} })],
  advanced: { database: { validateSchema: false } },
});
const version = JSON.parse(readFileSync(new URL("../node_modules/better-auth/package.json", import.meta.url), "utf8")).version;

const { compileMigrations } = await getMigrations(auth.options);
const sql = await compileMigrations();
process.stdout.write(
  `-- Better Auth core tables (user, session, account, verification) plus rateLimit.\n` +
    `-- Generated by web/worker/scripts/auth-schema.mjs from better-auth ${version}. Do not edit by hand.\n` +
    sql.trim().replace(/;\s*(?=\S)/g, ";\n\n") +
    "\n",
);
